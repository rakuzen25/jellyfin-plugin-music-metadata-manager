export function requiredPage(): HTMLElement {
    const page = document.querySelector<HTMLElement>("#musicMetadataManagerPage");
    if (!page) throw new Error("Music Metadata Manager settings page is missing");
    return page;
}
export function lookup(page: HTMLElement) {
    function q<K extends keyof PageElements>(id: K): PageElements[K];
    function q<E extends HTMLElement = HTMLElement>(id: string): E;
    function q(id: string): HTMLElement {
        const element = page.querySelector<HTMLElement>("#" + CSS.escape(id));
        if (!element) throw new Error("Settings control is missing: " + id);
        return element;
    }
    return q;
}
export function optionalLookup(page: HTMLElement) {
    function find<K extends keyof PageElements>(id: K): PageElements[K] | null;
    function find<E extends HTMLElement = HTMLElement>(id: string): E | null;
    function find(id: string): HTMLElement | null {
        return page.querySelector<HTMLElement>("#" + CSS.escape(id));
    }
    return find;
}
